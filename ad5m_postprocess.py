#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
ad5m_postprocess.py — единый пост-процессор OrcaSlicer для
Flashforge Adventurer 5M / 5M Pro с прошивкой zmod (+ Moonraker/Fluidd/Spoolman).

Что делает (за один проход, в правильном порядке):
  1. Убирает старые строки "; MD5:" (можно запускать повторно — без дублей).
  2. Копирует время печати "; estimated printing time (normal mode) = ..."
     в заголовок файла — штатный экран показывает оставшееся время.
  3. Проверяет метаданные, по которым Moonraker/Fluidd/Spoolman определяют
     слайсер и филамент. Если какие-то поля пропали (например, их убил другой
     скрипт), дописывает их копию в конец файла, где их ищет Moonraker.
  4. Последним шагом считает MD5 и ставит "; MD5:<hash>" первой строкой
     (формат CHECK_MD5 / FORCE_MD5 из zmod).

Работает только на стандартной библиотеке Python 3.7+, сохраняет исходные
окончания строк (LF/CRLF), пишет файл атомарно.

Подключение в OrcaSlicer:
  Процесс → Прочее → Скрипты постобработки:
    Windows:     "C:\\Python312\\python.exe" "C:\\Scripts\\ad5m_postprocess.py";
    Linux/macOS: /usr/bin/python3 /home/user/scripts/ad5m_postprocess.py;
  Старые скрипты (время и MD5) из списка удалить.

Диагностика готового файла (ничего не меняет):
  python ad5m_postprocess.py --check file.gcode

Общий принцип: файл целиком читается в память и обрабатывается как байты
(bytes), а не как текст. Так MD5 считается ровно по тому, что окажется
на диске, не нужно угадывать кодировку (в именах профилей бывает что угодно)
и не меняются окончания строк.
"""

import hashlib
import os
import re
import sys
import tempfile

# ---------------------------------------------------------------------------
# Константы
# ---------------------------------------------------------------------------

# Первая строка, которую ждёт zmod: "; MD5:<32 hex-символа>". Хеш считается
# по всему содержимому файла ПОСЛЕ этой строки.
MD5_PREFIX = b"; MD5:"

# Ключ строки времени печати. OrcaSlicer пишет её в конце файла:
#   ; estimated printing time (normal mode) = 1h 2m 3s
TIME_KEY = b"estimated printing time (normal mode)"

# Если в файле нет маркера "; HEADER_BLOCK_END", заголовком считаются
# первые HEADER_LINES_LIMIT строк — в них ищется и туда вставляется время.
HEADER_LINES_LIMIT = 300

# Moonraker разбирает метаданные только по первым и последним 512 КБ файла:
# в начале ищет строку "generated by ...", в конце — поля филамента и время.
# Всё, что лежит в середине, он не видит.
MOONRAKER_READ_SIZE = 512 * 1024

# Маркеры блока, который скрипт дописывает в конец файла с восстановленными
# полями. По ним же блок находится и удаляется при повторном запуске.
PP_BLOCK_START = b"; AD5M_PP_METADATA_START"
PP_BLOCK_END = b"; AD5M_PP_METADATA_END"

# Поля, по которым Moonraker (парсер OrcaSlicer/PrusaSlicer) собирает
# метаданные филамента для Fluidd и проверок Spoolman.
FILAMENT_KEYS = [
    b"filament_type",           # PLA, PETG, ... — Fluidd и Spoolman
    b"filament_settings_id",    # имя профиля филамента
    b"filament_colour",         # цвет для превью
    b"filament_vendor",
    b"filament_density",        # нужны для пересчёта длины в вес
    b"filament_diameter",
    b"filament used [mm]",      # расход по длине
    b"filament used [g]",       # расход по весу — Spoolman списывает остаток
    b"total filament used [g]",
    b"total filament weight [g]",
]
# Всё, что должно оказаться в последних 512 КБ файла.
FOOTER_KEYS = FILAMENT_KEYS + [TIME_KEY]

# Строка, по которой Moonraker определяет слайсер (и, значит, каким парсером
# читать метаданные). Например: "; generated by OrcaSlicer 2.1.1 on ...".
# re.MULTILINE — чтобы "^" означал начало любой строки, а не только файла.
SLICER_RE = re.compile(rb"^;\s*generated by (OrcaSlicer|Orca|PrusaSlicer|SuperSlicer)[^\r\n]*",
                       re.MULTILINE)


# ---------------------------------------------------------------------------
# Вспомогательные функции
# ---------------------------------------------------------------------------

def log(msg):
    # В stderr, а не в stdout: OrcaSlicer показывает именно stderr, если
    # скрипт завершился с ошибкой. Префикс помогает найти наши строки в логе.
    sys.stderr.write("[ad5m_postprocess] %s\n" % msg)


def detect_eol(data):
    # Определяем окончание строк по первым 64 КБ: OrcaSlicer пишет весь файл
    # в одном стиле, а сканировать сотни мегабайт ради этого незачем.
    # Новые строки (время, MD5, блок метаданных) пишутся в том же стиле.
    return b"\r\n" if b"\r\n" in data[:65536] else b"\n"


def strip_md5_lines(data):
    """Удаляет все строки '; MD5:' в начале файла (повторный запуск, старые скрипты)."""
    # Строк может быть несколько, если раньше файл прошёл через разные
    # MD5-скрипты, — снимаем их по одной, пока начало файла не станет чистым.
    while data.startswith(MD5_PREFIX):
        nl = data.find(b"\n")
        # Нет перевода строки — значит, в файле только строка MD5.
        data = b"" if nl < 0 else data[nl + 1:]
    return data


def find_key_line(data, key, from_end=False):
    """Ищет строку вида '; <key> = value'. Возвращает (start, end) или None."""
    # Шаблон: ";", пробелы, ключ, пробелы, "=", затем всё до конца строки.
    # re.escape нужен, потому что в ключах есть "[" и "]" ("filament used [g]").
    # Найденный диапазон не включает перевод строки (но может включать "\r"
    # из CRLF — вызывающий код при необходимости делает rstrip()).
    # [ \t] вместо \s: пустое значение не должно захватывать следующую строку
    pat = re.compile(rb"^;[ \t]*" + re.escape(key) + rb"[ \t]*=[^\r\n]*", re.MULTILINE)
    if not from_end:
        m = pat.search(data)
        return (m.start(), m.end()) if m else None

    # Ищем с конца окнами растущего размера, чтобы не сканировать весь файл:
    # нужные поля почти всегда лежат в последних сотнях килобайт.
    # Первое окно — последние 512 КБ, каждое следующее вдвое больше и
    # заканчивается там, где началось предыдущее, так что каждый байт
    # просматривается не больше одного раза.
    end, size = len(data), MOONRAKER_READ_SIZE
    while end > 0:
        start = max(0, end - size)
        if start:
            start = data.rfind(b"\n", 0, start) + 1  # окно начинается с начала строки
        # Внутри окна нужно последнее совпадение — оно ближе всего к концу файла
        # и соответствует итоговому значению, если ключ встречается несколько раз.
        last = None
        for m in pat.finditer(data, start, end):
            last = m
        if last:
            return last.start(), last.end()
        end, size = start, size * 2
    return None


def header_region_end(data):
    """Конец области заголовка: '; HEADER_BLOCK_END' или первые N строк."""
    # OrcaSlicer обрамляет заголовок строками "; HEADER_BLOCK_START" и
    # "; HEADER_BLOCK_END". Маркер ищем только в начале файла: если его нет
    # в первых 512 КБ, то нет и вообще, а сканировать весь файл дорого.
    m = re.search(rb"^;\s*HEADER_BLOCK_END[^\r\n]*\r?\n", data[:MOONRAKER_READ_SIZE], re.MULTILINE)
    if m:
        return m.end()
    # Маркера нет (другой слайсер или его убрал другой скрипт) — отсчитываем
    # первые HEADER_LINES_LIMIT строк.
    pos = 0
    for _ in range(HEADER_LINES_LIMIT):
        nl = data.find(b"\n", pos)
        if nl < 0:
            return len(data)  # файл короче лимита — заголовок занимает его целиком
        pos = nl + 1
    return pos


# ---------------------------------------------------------------------------
# Шаги обработки. Каждый принимает и возвращает содержимое файла (bytes)
# плюс сообщение для лога — так шаги легко выстраиваются в цепочку.
# ---------------------------------------------------------------------------

def ensure_time_in_header(data, eol):
    """Добавляет строку времени в заголовок, если её там ещё нет."""
    # Экран принтера берёт время печати из начала файла, а OrcaSlicer
    # пишет его только в конец. Копируем строку наверх.
    hdr_end = header_region_end(data)
    if find_key_line(data[:hdr_end], TIME_KEY):
        # Уже есть — например, файл обрабатывается повторно.
        return data, "время уже есть в заголовке"

    # Берём последнее вхождение в файле — это итоговая строка OrcaSlicer.
    span = find_key_line(data, TIME_KEY, from_end=True)
    if not span:
        return data, "ВНИМАНИЕ: OrcaSlicer не записал время печати — пропускаю"
    time_line = data[span[0]:span[1]].rstrip()  # rstrip убирает "\r" из CRLF

    # Вставляем сразу после '; HEADER_BLOCK_START' или после '; generated by ...'
    # Если нет ни того, ни другого — в самое начало файла.
    m = re.search(rb"^;\s*HEADER_BLOCK_START[^\r\n]*\r?\n", data[:hdr_end], re.MULTILINE)
    if not m:
        m = SLICER_RE.search(data[:hdr_end])
        if m:
            # SLICER_RE не захватывает перевод строки, поэтому вставляем
            # после ближайшего "\n" — то есть на начало следующей строки.
            nl = data.find(b"\n", m.end())
            insert_at = nl + 1 if nl >= 0 else m.end()
        else:
            insert_at = 0
    else:
        insert_at = m.end()  # шаблон уже включает перевод строки

    data = data[:insert_at] + time_line + eol + data[insert_at:]
    return data, "время добавлено в заголовок: %s" % time_line.decode("utf-8", "replace")


def ensure_filament_metadata(data, eol):
    """
    Moonraker ищет поля филамента в последних 512 КБ файла. Если поле есть
    где-то в файле, но не попадает в эту область — дописываем копию в конец.
    """
    # Удаляем наш блок от прошлого запуска
    # (DOTALL — чтобы ".*?" проходил через переводы строк; "?" — нежадный
    # поиск, чтобы не захватить лишнее между двумя разными блоками).
    # Без этого при повторном запуске блоки бы копились, а поля из старого
    # блока считались бы «уже есть в конце» и не обновлялись.
    data = re.sub(re.escape(PP_BLOCK_START) + rb".*?" + re.escape(PP_BLOCK_END) + rb"\r?\n?",
                  b"", data, flags=re.DOTALL)

    # Область, которую увидит Moonraker.
    footer_start = max(0, len(data) - MOONRAKER_READ_SIZE)
    footer = data[footer_start:]
    restored, missing = [], []  # restored — строки для копирования, missing — ключи, которых нет нигде

    for key in FOOTER_KEYS:
        if find_key_line(footer, key):
            continue  # Moonraker поле и так увидит
        span = find_key_line(data, key, from_end=True)
        if span:
            restored.append(data[span[0]:span[1]].rstrip())
        else:
            missing.append(key.decode())

    notes = []
    if restored:
        # Блок должен начинаться с новой строки, иначе склеится с последней.
        if not data.endswith(b"\n"):
            data += eol
        data += PP_BLOCK_START + eol + eol.join(restored) + eol + PP_BLOCK_END + eol
        notes.append("восстановлено полей для Moonraker: %d" % len(restored))

    # Об отсутствии необязательных полей (цвет, производитель и т.п.) молчим,
    # а без этих трёх Fluidd/Spoolman не покажут филамент и расход.
    important = {"filament_type", "filament_settings_id", "filament used [g]"}
    lost = [k for k in missing if k in important]
    if lost:
        notes.append("ВНИМАНИЕ: в файле нет %s — проверьте, что в OrcaSlicer не отключён "
                     "блок конфигурации в G-коде" % ", ".join(lost))

    # Строку слайсера не восстанавливаем — только предупреждаем: её место
    # в начале файла, и подставлять туда выдуманную версию слайсера не стоит.
    if not SLICER_RE.search(data[:MOONRAKER_READ_SIZE]):
        notes.append("ВНИМАНИЕ: нет строки '; generated by OrcaSlicer ...' в начале файла — "
                     "Moonraker не узнает слайсер и Fluidd не покажет филамент")
    return data, "; ".join(notes) or "метаданные филамента в порядке"


def add_md5(data, eol):
    # Хеш считается по всему файлу без строки MD5, а сама строка ставится
    # первой. Поэтому этот шаг обязан быть последним: любое изменение
    # после него сделает хеш неверным, и zmod откажется печатать файл.
    digest = hashlib.md5(data).hexdigest()
    return MD5_PREFIX + digest.encode() + eol + data, digest


def write_atomic(path, data):
    # Сначала пишем во временный файл, затем подменяем им исходный.
    # Если запись прервётся (нет места, сбой), исходный файл останется
    # нетронутым, а не обрезанным наполовину.
    # Временный файл создаём в той же папке: os.replace атомарен только
    # в пределах одного диска. Точка в начале имени скрывает его в Linux.
    d = os.path.dirname(os.path.abspath(path))
    fd, tmp = tempfile.mkstemp(prefix=".ad5m_pp_", dir=d)
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(data)
        os.replace(tmp, path)
    except Exception:
        # Не оставляем мусор рядом с G-кодом и пробрасываем ошибку дальше.
        if os.path.exists(tmp):
            os.remove(tmp)
        raise


# ---------------------------------------------------------------------------
# Режимы работы
# ---------------------------------------------------------------------------

def process(path):
    """Основной режим: обрабатывает файл на месте."""
    with open(path, "rb") as f:
        data = f.read()
    eol = detect_eol(data)

    # Порядок шагов важен: старые MD5 снимаются первыми (иначе они попадут
    # в хеш и сдвинут заголовок), новый MD5 считается последним.
    # Пишем в лог сразу после каждого шага: если запись файла упадёт,
    # результаты предыдущих шагов всё равно останутся в выводе.
    data = strip_md5_lines(data)
    data, msg = ensure_time_in_header(data, eol)
    log(msg)
    data, msg = ensure_filament_metadata(data, eol)
    log(msg)
    data, digest = add_md5(data, eol)  # строго последним шагом
    log("MD5: %s" % digest)

    write_atomic(path, data)


def check(path):
    """Режим --check: проверяет готовый файл, ничего не меняя. 0 — всё в порядке, 2 — нет."""
    # Код 2, а не 1, чтобы отличать «файл с проблемами» от «скрипт упал».
    with open(path, "rb") as f:
        data = f.read()
    ok = True
    print("Файл:", path)

    # 1. MD5: пересчитываем хеш и сравниваем с записанным.
    if data.startswith(MD5_PREFIX):
        first, _, rest = data.partition(b"\n")  # без перевода строки rest пустой
        # strip() убирает "\r" из CRLF; "replace" — чтобы мусор в строке
        # не ронял проверку, а просто дал несовпадение.
        stored = first[len(MD5_PREFIX):].strip().decode("ascii", "replace")
        real = hashlib.md5(rest).hexdigest()
        good = stored == real
        ok &= good
        print("  MD5 в первой строке:", "OK" if good else "НЕ СОВПАДАЕТ (%s != %s)" % (stored, real))
    else:
        ok = False
        print("  MD5 в первой строке: нет")

    # Дальнейшие проверки — по файлу без строки MD5, как его видит process().
    # 2. Время в заголовке — для экрана принтера.
    body = strip_md5_lines(data)
    hdr = find_key_line(body[:header_region_end(body)], TIME_KEY)
    print("  Время в заголовке:", body[hdr[0]:hdr[1]].decode("utf-8", "replace") if hdr else "нет")
    ok &= bool(hdr)

    # 3. Строка слайсера в первых 512 КБ — там её ищет Moonraker.
    m = SLICER_RE.search(body[:MOONRAKER_READ_SIZE])
    print("  Слайсер для Moonraker:", m.group(0).decode("utf-8", "replace") if m else "НЕ ОПРЕДЕЛЁН")
    ok &= bool(m)

    # 4. Поля филамента в последних 512 КБ. Только выводим: часть полей
    # необязательна, поэтому на код возврата они не влияют.
    footer = body[-MOONRAKER_READ_SIZE:]
    print("  Поля филамента, которые увидит Moonraker:")
    for key in FILAMENT_KEYS:
        span = find_key_line(footer, key)
        val = footer[span[0]:span[1]].decode("utf-8", "replace") if span else "— нет —"
        # Длинные значения (списки для многоцветной печати) обрезаем.
        print("    ", val if len(val) < 120 else val[:117] + "...")
    return 0 if ok else 2


def use_utf8_for_pipes():
    """
    В pipe (OrcaSlicer, перенаправление в файл) Python на Windows пишет
    в cp1251, и кириллица превращается в мусор. Консоль не трогаем.
    """
    # stream бывает None, если exe собран без консоли (pythonw, --noconsole).
    # reconfigure есть начиная с Python 3.7 — проверка на всякий случай.
    for stream in (sys.stdout, sys.stderr):
        if stream is not None and not stream.isatty() and hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8")


def main(argv):
    """Разбор аргументов. Возвращает код выхода процесса."""
    use_utf8_for_pipes()
    if len(argv) >= 3 and argv[1] == "--check":
        return check(argv[2])
    if len(argv) < 2:
        log("использование: ad5m_postprocess.py <file.gcode> | --check <file.gcode>")
        return 1
    path = argv[-1]  # OrcaSlicer передаёт путь к файлу последним аргументом
    try:
        process(path)
        return 0
    except Exception as e:  # ненулевой код — OrcaSlicer покажет ошибку при экспорте
        log("ОШИБКА: %s" % e)
        return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
