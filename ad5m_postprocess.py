#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
ad5m_postprocess.py — единый пост-процессор OrcaSlicer для
Flashforge Adventurer 5M / 5M Pro с прошивкой zmod (+ Moonraker/Fluidd/Spoolman).

Что делает (за один проход, в правильном порядке):
  1. Убирает старые строки "; MD5:" (можно запускать повторно — без дублей).
  2. Копирует время печати "; estimated printing time (normal mode) = ..."
     в заголовок файла — штатный экран показывает оставшееся время.
  3. Проверяет метаданные, по которым Moonraker/Fluidd/Spoolman определяют
     слайсер и филамент. Если какие-то поля пропали (например, их убил другой
     скрипт), дописывает их копию в конец файла, где их ищет Moonraker.
  4. Последним шагом считает MD5 и ставит "; MD5:<hash>" первой строкой
     (формат CHECK_MD5 / FORCE_MD5 из zmod).

Работает только на стандартной библиотеке Python 3.7+, сохраняет исходные
окончания строк (LF/CRLF), пишет файл атомарно.

Подключение в OrcaSlicer:
  Процесс → Прочее → Скрипты постобработки:
    Windows:     "C:\\Python312\\python.exe" "C:\\Scripts\\ad5m_postprocess.py";
    Linux/macOS: /usr/bin/python3 /home/user/scripts/ad5m_postprocess.py;
  Старые скрипты (время и MD5) из списка удалить.

Диагностика готового файла (ничего не меняет):
  python ad5m_postprocess.py --check file.gcode
"""

import hashlib
import os
import re
import sys
import tempfile

MD5_PREFIX = b"; MD5:"
TIME_KEY = b"; estimated printing time (normal mode)"
HEADER_LINES_LIMIT = 300          # где искать строку времени в заголовке
MOONRAKER_READ_SIZE = 512 * 1024  # сколько Moonraker читает с начала/конца файла
PP_BLOCK_START = b"; AD5M_PP_METADATA_START"
PP_BLOCK_END = b"; AD5M_PP_METADATA_END"

# Поля, по которым Moonraker (парсер OrcaSlicer/PrusaSlicer) собирает
# метаданные филамента для Fluidd и проверок Spoolman.
FILAMENT_KEYS = [
    b"filament_type",
    b"filament_settings_id",
    b"filament_colour",
    b"filament_vendor",
    b"filament_density",
    b"filament_diameter",
    b"filament used [mm]",
    b"filament used [g]",
    b"total filament used [g]",
    b"total filament weight [g]",
    b"estimated printing time (normal mode)",
]

SLICER_RE = re.compile(rb"^;\s*generated by (OrcaSlicer|Orca|PrusaSlicer|SuperSlicer)[^\r\n]*",
                       re.MULTILINE)


def log(msg):
    sys.stderr.write("[ad5m_postprocess] %s\n" % msg)


def detect_eol(data):
    return b"\r\n" if b"\r\n" in data[:65536] else b"\n"


def strip_md5_lines(data):
    """Удаляет все строки '; MD5:' в начале файла (повторный запуск, старые скрипты)."""
    while data.startswith(MD5_PREFIX):
        nl = data.find(b"\n")
        data = b"" if nl < 0 else data[nl + 1:]
    return data


def find_key_line(data, key, from_end=False):
    """Ищет строку вида '; <key> = value'. Возвращает (start, end) или None."""
    pat = re.compile(rb"^;\s*" + re.escape(key) + rb"\s*=\s*[^\r\n]*", re.MULTILINE)
    if not from_end:
        m = pat.search(data)
        return (m.start(), m.end()) if m else None
    last = None
    for m in pat.finditer(data):
        last = m
    return (last.start(), last.end()) if last else None


def header_region_end(data):
    """Конец области заголовка: '; HEADER_BLOCK_END' или первые N строк."""
    m = re.search(rb"^;\s*HEADER_BLOCK_END[^\r\n]*\r?\n", data[:MOONRAKER_READ_SIZE], re.MULTILINE)
    if m:
        return m.end()
    pos = 0
    for _ in range(HEADER_LINES_LIMIT):
        nl = data.find(b"\n", pos)
        if nl < 0:
            return len(data)
        pos = nl + 1
    return pos


def ensure_time_in_header(data, eol):
    """Добавляет строку времени в заголовок, если её там ещё нет."""
    hdr_end = header_region_end(data)
    if find_key_line(data[:hdr_end], TIME_KEY[2:]):
        return data, "время уже есть в заголовке"

    span = find_key_line(data, TIME_KEY[2:], from_end=True)
    if not span:
        return data, "ВНИМАНИЕ: OrcaSlicer не записал время печати — пропускаю"
    time_line = data[span[0]:span[1]].rstrip()

    # Вставляем сразу после '; HEADER_BLOCK_START' или после '; generated by ...'
    m = re.search(rb"^;\s*HEADER_BLOCK_START[^\r\n]*\r?\n", data[:hdr_end], re.MULTILINE)
    if not m:
        m = SLICER_RE.search(data[:hdr_end])
        if m:
            nl = data.find(b"\n", m.end())
            insert_at = nl + 1 if nl >= 0 else m.end()
        else:
            insert_at = 0
    else:
        insert_at = m.end()

    data = data[:insert_at] + time_line + eol + data[insert_at:]
    return data, "время добавлено в заголовок: %s" % time_line.decode("utf-8", "replace")


def ensure_filament_metadata(data, eol):
    """
    Moonraker ищет поля филамента в последних 512 КБ файла. Если поле есть
    где-то в файле, но не попадает в эту область — дописываем копию в конец.
    """
    # Удаляем наш блок от прошлого запуска
    data = re.sub(re.escape(PP_BLOCK_START) + rb".*?" + re.escape(PP_BLOCK_END) + rb"\r?\n?",
                  b"", data, flags=re.DOTALL)

    footer_start = max(0, len(data) - MOONRAKER_READ_SIZE)
    footer = data[footer_start:]
    restored, missing = [], []

    for key in FILAMENT_KEYS:
        if find_key_line(footer, key):
            continue
        span = find_key_line(data, key, from_end=True)
        if span:
            restored.append(data[span[0]:span[1]].rstrip())
        else:
            missing.append(key.decode())

    notes = []
    if restored:
        if not data.endswith(b"\n"):
            data += eol
        data += PP_BLOCK_START + eol + eol.join(restored) + eol + PP_BLOCK_END + eol
        notes.append("восстановлено полей для Moonraker: %d" % len(restored))

    important = {"filament_type", "filament_settings_id", "filament used [g]"}
    lost = [k for k in missing if k in important]
    if lost:
        notes.append("ВНИМАНИЕ: в файле нет %s — проверьте, что в OrcaSlicer не отключён "
                     "блок конфигурации в G-коде" % ", ".join(lost))

    if not SLICER_RE.search(data[:MOONRAKER_READ_SIZE]):
        notes.append("ВНИМАНИЕ: нет строки '; generated by OrcaSlicer ...' в начале файла — "
                     "Moonraker не узнает слайсер и Fluidd не покажет филамент")
    return data, "; ".join(notes) or "метаданные филамента в порядке"


def add_md5(data, eol):
    digest = hashlib.md5(data).hexdigest()
    return MD5_PREFIX + digest.encode() + eol + data, digest


def write_atomic(path, data):
    d = os.path.dirname(os.path.abspath(path))
    fd, tmp = tempfile.mkstemp(prefix=".ad5m_pp_", dir=d)
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(data)
        os.replace(tmp, path)
    except Exception:
        if os.path.exists(tmp):
            os.remove(tmp)
        raise


def process(path):
    with open(path, "rb") as f:
        data = f.read()
    eol = detect_eol(data)

    data = strip_md5_lines(data)
    data, msg_time = ensure_time_in_header(data, eol)
    data, msg_meta = ensure_filament_metadata(data, eol)
    data, digest = add_md5(data, eol)  # строго последним шагом

    write_atomic(path, data)
    log(msg_time)
    log(msg_meta)
    log("MD5: %s" % digest)


def check(path):
    with open(path, "rb") as f:
        data = f.read()
    ok = True
    print("Файл:", path)

    if data.startswith(MD5_PREFIX):
        nl = data.find(b"\n")
        stored = data[len(MD5_PREFIX):nl].strip().decode()
        real = hashlib.md5(data[nl + 1:]).hexdigest()
        good = stored == real
        ok &= good
        print("  MD5 в первой строке:", "OK" if good else "НЕ СОВПАДАЕТ (%s != %s)" % (stored, real))
    else:
        ok = False
        print("  MD5 в первой строке: нет")

    body = strip_md5_lines(data)
    hdr = find_key_line(body[:header_region_end(body)], TIME_KEY[2:])
    print("  Время в заголовке:", body[hdr[0]:hdr[1]].decode("utf-8", "replace") if hdr else "нет")
    ok &= bool(hdr)

    m = SLICER_RE.search(body[:MOONRAKER_READ_SIZE])
    print("  Слайсер для Moonraker:", m.group(0).decode("utf-8", "replace") if m else "НЕ ОПРЕДЕЛЁН")
    ok &= bool(m)

    footer = body[-MOONRAKER_READ_SIZE:]
    print("  Поля филамента, которые увидит Moonraker:")
    for key in FILAMENT_KEYS[:-1]:
        span = find_key_line(footer, key)
        val = footer[span[0]:span[1]].decode("utf-8", "replace") if span else "— нет —"
        print("    ", val if len(val) < 120 else val[:117] + "...")
    return 0 if ok else 2


def main(argv):
    if len(argv) >= 3 and argv[1] == "--check":
        return check(argv[2])
    if len(argv) < 2:
        log("использование: ad5m_postprocess.py <file.gcode> | --check <file.gcode>")
        return 1
    path = argv[-1]  # OrcaSlicer передаёт путь к файлу последним аргументом
    try:
        process(path)
        return 0
    except Exception as e:  # ненулевой код — OrcaSlicer покажет ошибку при экспорте
        log("ОШИБКА: %s" % e)
        return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
