"""Тесты ad5m_postprocess.py. Запуск: python -m unittest discover -s tests -v"""

import contextlib
import hashlib
import io
import os
import sys
import tempfile
import unittest

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import ad5m_postprocess as pp  # noqa: E402

TIME_LINE = "; estimated printing time (normal mode) = 1h 2m 3s"

CONFIG_BLOCK = [
    "; CONFIG_BLOCK_START",
    "; filament_type = PLA",
    "; filament_settings_id = \"Generic PLA @AD5M\"",
    "; filament_colour = #FF0000",
    "; filament_vendor = Generic",
    "; filament_density = 1.24",
    "; filament_diameter = 1.75",
    "; CONFIG_BLOCK_END",
]


def make_gcode(eol="\n", header_block=True, with_time=True, config_at_start=False,
               moves=10):
    """Синтетический G-код в формате OrcaSlicer."""
    lines = []
    if header_block:
        lines.append("; HEADER_BLOCK_START")
    lines.append("; generated by OrcaSlicer 2.1.1 on 2026-11-01 at 12:00:00")
    lines.append("; total layer number: 10")
    if header_block:
        lines.append("; HEADER_BLOCK_END")
    if config_at_start:
        lines += CONFIG_BLOCK
    lines += ["G1 X%d Y%d E0.05" % (i % 200, i % 200) for i in range(moves)]
    lines += [
        "; filament used [mm] = 1000.00",
        "; filament used [g] = 3.00",
        "; total filament used [g] = 3.00",
        "; total filament weight [g] = 3.00",
    ]
    if with_time:
        lines.append(TIME_LINE)
    if not config_at_start:
        lines += CONFIG_BLOCK
    return (eol.join(lines) + eol).encode()


class Base(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)

    def write(self, data, name="test.gcode"):
        path = os.path.join(self.tmp.name, name)
        with open(path, "wb") as f:
            f.write(data)
        return path

    def read(self, path):
        with open(path, "rb") as f:
            return f.read()

    def run_process(self, path):
        err = io.StringIO()
        with contextlib.redirect_stderr(err):
            pp.process(path)
        return err.getvalue()

    def run_check(self, path):
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            rc = pp.check(path)
        return rc, out.getvalue()


class TestProcess(Base):
    def test_md5_first_line_matches_body(self):
        path = self.write(make_gcode())
        self.run_process(path)
        data = self.read(path)
        first, _, body = data.partition(b"\n")
        self.assertTrue(first.startswith(b"; MD5:"))
        self.assertEqual(first[len(b"; MD5:"):].decode(), hashlib.md5(body).hexdigest())

    def test_time_inserted_after_header_block_start(self):
        path = self.write(make_gcode())
        self.run_process(path)
        lines = self.read(path).split(b"\n")
        self.assertEqual(lines[1], b"; HEADER_BLOCK_START")
        self.assertEqual(lines[2], TIME_LINE.encode())

    def test_time_inserted_after_generated_by_without_header_block(self):
        # без HEADER_BLOCK_END заголовком считаются первые 300 строк
        path = self.write(make_gcode(header_block=False, moves=pp.HEADER_LINES_LIMIT))
        self.run_process(path)
        lines = self.read(path).split(b"\n")
        self.assertTrue(lines[1].startswith(b"; generated by OrcaSlicer"))
        self.assertEqual(lines[2], TIME_LINE.encode())

    def test_idempotent(self):
        path = self.write(make_gcode())
        self.run_process(path)
        once = self.read(path)
        self.run_process(path)
        self.assertEqual(self.read(path), once)

    def test_idempotent_with_restored_metadata(self):
        path = self.write(make_gcode(config_at_start=True, moves=40000))
        self.run_process(path)
        once = self.read(path)
        self.run_process(path)
        self.assertEqual(self.read(path), once)
        self.assertEqual(once.count(pp.PP_BLOCK_START), 1)

    def test_old_md5_lines_removed(self):
        data = b"; MD5:aaaa\n; MD5:bbbb\n" + make_gcode()
        path = self.write(data)
        self.run_process(path)
        self.assertEqual(self.read(path).count(b"; MD5:"), 1)

    def test_crlf_preserved(self):
        path = self.write(make_gcode(eol="\r\n"))
        self.run_process(path)
        data = self.read(path)
        self.assertEqual(data.count(b"\n"), data.count(b"\r\n"))
        self.assertEqual(self.run_check(path)[0], 0)

    def test_missing_time_warns_but_adds_md5(self):
        path = self.write(make_gcode(with_time=False))
        log = self.run_process(path)
        self.assertIn("не записал время", log)
        self.assertTrue(self.read(path).startswith(b"; MD5:"))

    def test_metadata_restored_when_outside_footer(self):
        path = self.write(make_gcode(config_at_start=True, moves=40000))
        self.assertGreater(os.path.getsize(path), pp.MOONRAKER_READ_SIZE)
        log = self.run_process(path)
        self.assertIn("восстановлено полей", log)
        data = self.read(path)
        footer = data[-pp.MOONRAKER_READ_SIZE:]
        for key in (b"filament_type", b"filament_settings_id", b"filament_colour"):
            self.assertIsNotNone(pp.find_key_line(footer, key), key)
        self.assertEqual(self.run_check(path)[0], 0)

    def test_no_metadata_block_when_footer_is_complete(self):
        path = self.write(make_gcode())
        log = self.run_process(path)
        self.assertIn("в порядке", log)
        self.assertNotIn(pp.PP_BLOCK_START, self.read(path))

    def test_missing_important_fields_warns(self):
        data = make_gcode().replace(b"; filament_type = PLA\n", b"")
        path = self.write(data)
        log = self.run_process(path)
        self.assertIn("filament_type", log)

    def test_missing_slicer_line_warns(self):
        data = make_gcode().replace(b"; generated by OrcaSlicer", b"; made by Other")
        path = self.write(data)
        log = self.run_process(path)
        self.assertIn("generated by", log)

    def test_no_temp_files_left(self):
        path = self.write(make_gcode())
        self.run_process(path)
        self.assertEqual(os.listdir(self.tmp.name), ["test.gcode"])


class TestCheck(Base):
    def test_processed_file_ok(self):
        path = self.write(make_gcode())
        self.run_process(path)
        rc, out = self.run_check(path)
        self.assertEqual(rc, 0)
        self.assertIn("OK", out)
        self.assertIn("filament_type = PLA", out)

    def test_check_does_not_modify_file(self):
        path = self.write(make_gcode())
        before = self.read(path)
        self.run_check(path)
        self.assertEqual(self.read(path), before)

    def test_unprocessed_file_fails(self):
        path = self.write(make_gcode())
        rc, out = self.run_check(path)
        self.assertEqual(rc, 2)
        self.assertIn("MD5 в первой строке: нет", out)

    def test_tampered_file_fails(self):
        path = self.write(make_gcode())
        self.run_process(path)
        self.write(self.read(path) + b"G1 X1\n")
        rc, out = self.run_check(path)
        self.assertEqual(rc, 2)
        self.assertIn("НЕ СОВПАДАЕТ", out)


class TestFindKeyLine(unittest.TestCase):
    def test_empty_value_does_not_capture_next_line(self):
        data = b"; filament_vendor = \n; filament_type = PLA\n"
        span = pp.find_key_line(data, b"filament_vendor")
        self.assertEqual(data[span[0]:span[1]], b"; filament_vendor = ")

    def test_from_end_finds_last_occurrence(self):
        data = b"; filament_type = ABS\n" + b"G1 X1\n" * 10 + b"; filament_type = PLA\n"
        span = pp.find_key_line(data, b"filament_type", from_end=True)
        self.assertEqual(data[span[0]:span[1]], b"; filament_type = PLA")

    def test_from_end_searches_beyond_first_window(self):
        line = b"; filament_type = PETG"
        data = line + b"\n" + b"G1 X1 Y1 E0.05\n" * 200000  # ~3 МБ, несколько окон
        span = pp.find_key_line(data, b"filament_type", from_end=True)
        self.assertEqual(span, (0, len(line)))

    def test_from_end_line_on_window_boundary(self):
        # строка с ключом пересекает границу первого окна
        tail = b"G1 X1\n" * (pp.MOONRAKER_READ_SIZE // 6)
        line = b"; filament_type = PLA"
        data = b"G1 X1\n" * 100 + line + b"\n" + tail[:-3] + b"\n"
        span = pp.find_key_line(data, b"filament_type", from_end=True)
        self.assertEqual(data[span[0]:span[1]], line)

    def test_from_end_missing(self):
        self.assertIsNone(pp.find_key_line(b"G1 X1\n" * 1000, b"filament_type", from_end=True))


class TestRegressions(Base):
    def test_check_md5_line_without_newline(self):
        path = self.write(b"; MD5:" + hashlib.md5(b"").hexdigest().encode())
        rc, out = self.run_check(path)
        self.assertIn("MD5 в первой строке: OK", out)

    def test_check_lists_only_filament_fields(self):
        path = self.write(make_gcode())
        self.run_process(path)
        out = self.run_check(path)[1]
        fields = out.split("Поля филамента, которые увидит Moonraker:")[1]
        self.assertEqual(len(fields.strip().splitlines()), len(pp.FILAMENT_KEYS))
        self.assertNotIn("estimated printing time", fields)

    def test_log_written_before_failed_write(self):
        path = self.write(make_gcode())
        original = pp.write_atomic

        def fail(*_):
            raise OSError("disk full")

        pp.write_atomic = fail
        self.addCleanup(setattr, pp, "write_atomic", original)
        err = io.StringIO()
        with contextlib.redirect_stderr(err):
            self.assertEqual(pp.main(["pp", path]), 1)
        log = err.getvalue()
        self.assertIn("время добавлено", log)
        self.assertIn("MD5:", log)
        self.assertIn("disk full", log)


class TestMain(Base):
    def call_main(self, argv):
        with contextlib.redirect_stderr(io.StringIO()), \
                contextlib.redirect_stdout(io.StringIO()):
            return pp.main(argv)

    def test_no_args(self):
        self.assertEqual(self.call_main(["pp"]), 1)

    def test_missing_file(self):
        self.assertEqual(self.call_main(["pp", os.path.join(self.tmp.name, "nope.gcode")]), 1)

    def test_path_is_last_argument(self):
        path = self.write(make_gcode())
        self.assertEqual(self.call_main(["pp", "--extra", path]), 0)
        self.assertTrue(self.read(path).startswith(b"; MD5:"))

    def test_check_mode(self):
        path = self.write(make_gcode())
        self.assertEqual(self.call_main(["pp", "--check", path]), 2)


if __name__ == "__main__":
    unittest.main()
